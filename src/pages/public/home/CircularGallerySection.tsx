export const CircularGallerySection: React.FC = () => {
  const [selectedPhoto, setSelectedPhoto] = useState<Photo | null>(null);
  const [isModalOpen, setIsModalOpen] = useState(false);

  const handleItemClick = (item: CircularGalleryItem, index: number) => {
    const itemData = ANIMAL_GALLERY_PHOTOS[index] || ANIMAL_GALLERY_PHOTOS[0];
    const photoToOpen = item.photo || itemData.fullPhoto;
    setSelectedPhoto(photoToOpen);
    setIsModalOpen(true);
  };

  return (
    <section className="pt-16 sm:pt-20 pb-14 sm:pb-20 bg-nature-dark border-t border-nature-border relative overflow-hidden">
      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 space-y-6">
        {/* Minimal Centered Header Matching Reference Image */}
        <div className="text-center max-w-2xl mx-auto space-y-1">
          <h2 className="font-serif text-2xl sm:text-3xl md:text-4xl font-semibold text-nature-parchment tracking-tight">
            Animal Gallery
          </h2>
          <p className="text-xs sm:text-sm text-nature-textMuted font-sans tracking-wide">
            Scroll or drag to rotate the 3D wildlife showcase
          </p>
        </div>

        {/* 3D Cylindrical Portrait Carousel with Smooth Drift & Depth */}
        <div className="relative w-full overflow-hidden">
          <CircularGallery
            items={ANIMAL_GALLERY_PHOTOS.map((a) => ({
              id: a.id,
              image: a.image,
              title: a.title,
              subtitle: a.subtitle,
              author: a.author,
              category: a.category,
              photo: a.fullPhoto,
            }))}
            bend={0}
            onItemClick={handleItemClick}
            autoplay={true}
          />
        </div>
      </div>

      {/* High-Resolution Photo Download & Details Modal */}
      <PhotoDownloadModal
        photo={selectedPhoto}
        isOpen={isModalOpen}
        onClose={() => setIsModalOpen(false)}
      />
    </section>
  );
};

export default CircularGallerySection;
